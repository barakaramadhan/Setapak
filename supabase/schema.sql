-- ---------------------------------------------------------
-- PLANNER DATA BERSAMA
-- Rekomendasi hasil AI untuk kota/area baru (mis. Kuta, Jepang)
-- disimpan di sini. Pencarian yang sama -> kartu yang sama untuk semua orang.
-- ---------------------------------------------------------
create table if not exists public.city_recommendations (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  city_key text not null,        -- kunci pencarian: kuta, jepang, bandung, ...
  city_label text not null,      -- nama yang diketik user, mis. "Kuta"
  area_mode text not null,       -- in | near
  min_rating numeric not null default 0,
  groups jsonb not null,         -- 2 kategori x 4 kartu
  source text not null,          -- provider AI yang pertama kali bikin
  constraint city_recommendations_key unique (city_key, area_mode, min_rating)
);

create index if not exists city_recommendations_city_idx
  on public.city_recommendations (city_key);

alter table public.city_recommendations enable row level security;
-- Sengaja tidak ada policy untuk anon: hanya service_role (server) yang bisa akses.

