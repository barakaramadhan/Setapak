-- ---------------------------------------------------------
-- JADWAL / TRIP USER (kalender + Schedule + halaman Trip)
-- Jalankan script ini ulang dengan aman: policy dibuat ulang,
-- tabel & index memakai "if not exists".
-- ---------------------------------------------------------
create extension if not exists pgcrypto;

create table if not exists public.trips (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  title text not null,
  trip_date date not null,             -- YYYY-MM-DD (tanggal mulai)
  end_date date,                       -- tanggal selesai; null = satu hari
  city text,                           -- mis. Bogor
  place text,                          -- nama tempat / ringkasan dari AI
  notes text,
  -- 15 modul Universal Trip Planner disimpan di sini (lihat src/utils/tripModules.js).
  -- Format lama hasil chat {city, days, totalCost} juga didukung.
  plan jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- Migration untuk database yang sudah punya tabel trips sebelumnya.
alter table public.trips add column if not exists end_date date;
update public.trips set end_date = trip_date where end_date is null;

create index if not exists trips_user_date_idx
  on public.trips (user_id, trip_date desc);

alter table public.trips enable row level security;

-- Hanya pemiliknya (auth.uid()) yang boleh melihat/ubah/hapus trip-nya.
-- Tidak ada policy untuk anon, jadi kunci browser tidak bisa membaca data ini.
drop policy if exists "trips_owner_select" on public.trips;
create policy "trips_owner_select" on public.trips
  for select to authenticated using (auth.uid() = user_id);

drop policy if exists "trips_owner_insert" on public.trips;
create policy "trips_owner_insert" on public.trips
  for insert to authenticated with check (auth.uid() = user_id);

drop policy if exists "trips_owner_update" on public.trips;
create policy "trips_owner_update" on public.trips
  for update to authenticated
  using (auth.uid() = user_id)
  with check (auth.uid() = user_id);

drop policy if exists "trips_owner_delete" on public.trips;
create policy "trips_owner_delete" on public.trips
  for delete to authenticated using (auth.uid() = user_id);

